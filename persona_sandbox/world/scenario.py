"""沙盒場景：壓力情境設計。

核心論點：名人對談只是鉤子。真正讓人格顯形的是**壓力**。
所以場景必須內建三件事：
  1. 稀缺      — 資源不夠所有人用
  2. 不對稱資訊 — 每個人知道的東西不一樣，而且不能全說
  3. 隱藏議程   — 每個人（包括使用者）都有一個不能公開的目標

另外一條關鍵機制：**內在獨白與對外發言必須分開，而且允許不一致（可以撒謊）。**
兩者一致的對話是廢話；兩者出現落差的地方，才是人格。
"""

from __future__ import annotations

from dataclasses import dataclass

