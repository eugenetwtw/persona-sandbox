"""名人角色卡。

法務原則：**MVP 只收已故歷史人物。** 已故者無肖像權／名譽權主張主體，且留下大量
可引用的一手文本（對話錄、道德經、演講稿）。在世名人的 skill 是社群零散製作的，
拿來當產品內容池風險不同。

角色卡沿用與人格卡相同的紀律：具體台詞，不寫形容詞；並附誠實邊界。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Witness:
    id: str
    name: str
    era: str
    archetype: str  # "對抗型" | "合作型" 等——用於配對設計
    deceased: bool
    sources: tuple[str, ...]
    card: str

    def short(self) -> str:
        return f"{self.name}（{self.era}，{self.archetype}）"


